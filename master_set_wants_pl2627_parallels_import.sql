insert into master_set_wants (card_id, variant, parallel_tier_id)
select c.id, 'normal', tier.tier_id
from target_numbers
join sets st on st.slug = 'grundset'
join cards c on c.set_id = st.id and c.number = target_numbers.card_number
cross join tier
where not exists (
  select 1 from master_set_wants w
  where w.card_id = c.id
    and w.variant = 'normal'
    and w.parallel_tier_id = tier.tier_id
);
